export const INGREDORA_TEMPLATE_PLATFORMS = [
  { id: 'youtube', label: 'YouTube' },
  { id: 'instagram', label: 'Instagram' },
  { id: 'tiktok', label: 'TikTok' },
  { id: 'facebook', label: 'Facebook' },
  { id: 'x', label: 'X' },
  { id: 'threads', label: 'Threads' },
] as const

// Posty's active publishing integrations. TikTok and X metadata are imported
// and retained, but those destinations are not published by the current app.
export const POSTY_PUBLISHING_PLATFORMS = [
  { id: 'youtube', label: 'YouTube' },
  { id: 'instagram', label: 'Instagram' },
  { id: 'facebook', label: 'Facebook' },
  { id: 'threads', label: 'Threads' },
] as const

export type PublishingPlatform = (typeof POSTY_PUBLISHING_PLATFORMS)[number]['id']
export type MetadataPlatform = (typeof INGREDORA_TEMPLATE_PLATFORMS)[number]['id']

export interface PlatformMetadata {
  title: string
  description: string
  hashtags: string
  tags: string
  pinnedComment: string
  altText: string
}

export interface ParsedIngredoraMetadata {
  version: 'INGREDORA_PUBLISHING_TEMPLATE_V1'
  global: PlatformMetadata
  platforms: Record<MetadataPlatform, PlatformMetadata>
  hasPlatformBlock: Record<MetadataPlatform, boolean>
  warnings: string[]
}

const FIELDS = [
  'TITLE',
  'DESCRIPTION',
  'HASHTAGS',
  'TAGS',
  'PINNED_COMMENT',
  'ALT_TEXT',
] as const

type TemplateField = (typeof FIELDS)[number]
type RawBlock = Partial<Record<TemplateField, string>>

const FIELD_TO_PROPERTY: Record<TemplateField, keyof PlatformMetadata> = {
  TITLE: 'title',
  DESCRIPTION: 'description',
  HASHTAGS: 'hashtags',
  TAGS: 'tags',
  PINNED_COMMENT: 'pinnedComment',
  ALT_TEXT: 'altText',
}

const emptyMetadata = (): PlatformMetadata => ({
  title: '',
  description: '',
  hashtags: '',
  tags: '',
  pinnedComment: '',
  altText: '',
})

function cleanValue(value: string | undefined): string {
  return (value ?? '').replace(/^["«]|["»]$/g, '').trim()
}

function toMetadata(block: RawBlock): PlatformMetadata {
  const result = emptyMetadata()

  for (const field of FIELDS) {
    result[FIELD_TO_PROPERTY[field]] = cleanValue(block[field])
  }

  return result
}

/**
 * Reads the publishing template generated by Ingredora Content Studio.
 *
 * Platform blocks override @GLOBAL field by field. If a platform block is
 * missing (for example @THREADS in older templates), all values inherit
 * from @GLOBAL so the import remains useful and predictable.
 */
export function parseIngredoraMetadata(input: string): ParsedIngredoraMetadata {
  const text = input.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n')
  const firstLine = text.split('\n', 1)[0]?.trim()

  if (firstLine !== 'INGREDORA_PUBLISHING_TEMPLATE_V1') {
    throw new Error(
      'Formato de TXT no reconocido. Se esperaba INGREDORA_PUBLISHING_TEMPLATE_V1.',
    )
  }

  const blocks: Record<string, RawBlock> = {}
  let currentBlock = ''
  let currentField: TemplateField | '' = ''
  let foundEnd = false

  for (const rawLine of text.split('\n').slice(1)) {
    const line = rawLine.trimEnd()
    const trimmed = line.trim()
    const marker = trimmed.match(/^@([A-Z][A-Z0-9_]*)$/i)

    if (marker) {
      currentBlock = marker[1].toLowerCase()
      if (currentBlock === 'end') {
        foundEnd = true
        break
      }

      blocks[currentBlock] ||= {}
      currentField = ''
      continue
    }

    if (!currentBlock) continue

    const fieldMatch = line.match(
      /^\s*(TITLE|DESCRIPTION|HASHTAGS|TAGS|PINNED_COMMENT|ALT_TEXT)\s*:\s?(.*)$/i,
    )

    if (fieldMatch) {
      currentField = fieldMatch[1].toUpperCase() as TemplateField
      blocks[currentBlock][currentField] = fieldMatch[2].trimEnd()
      continue
    }

    if (!currentField) continue

    // Keep wrapped lines and paragraph breaks inside multi-line fields.
    const previous = blocks[currentBlock][currentField] ?? ''
    if (!trimmed) {
      if (previous && !previous.endsWith('\n')) {
        blocks[currentBlock][currentField] = previous + '\n'
      }
      continue
    }

    blocks[currentBlock][currentField] = previous
      ? previous + '\n' + trimmed
      : trimmed
  }

  if (!blocks.global) {
    throw new Error('El TXT no contiene el bloque obligatorio @GLOBAL.')
  }

  const global = toMetadata(blocks.global)
  const platforms = {} as Record<MetadataPlatform, PlatformMetadata>
  const hasPlatformBlock = {} as Record<MetadataPlatform, boolean>

  for (const platform of INGREDORA_TEMPLATE_PLATFORMS) {
    const platformBlock = blocks[platform.id]
    hasPlatformBlock[platform.id] = !!platformBlock
    platforms[platform.id] = toMetadata({
      ...blocks.global,
      ...(platformBlock ?? {}),
    })
  }

  const warnings: string[] = []

  if (!foundEnd) {
    warnings.push('El TXT no contiene @END. Se importó el contenido disponible.')
  }

  if (!hasPlatformBlock.threads) {
    warnings.push(
      'El TXT no contiene @THREADS. Threads recibió los valores de @GLOBAL como punto de partida.',
    )
  }

  return {
    version: 'INGREDORA_PUBLISHING_TEMPLATE_V1',
    global,
    platforms,
    hasPlatformBlock,
    warnings,
  }
}
